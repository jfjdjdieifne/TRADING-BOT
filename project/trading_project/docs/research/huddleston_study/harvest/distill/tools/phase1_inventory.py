#!/usr/bin/env python3
"""Phase 1 inventory: (a) newsqlguru/ict-index transcript inventory,
(b) authorship flags per repository, from README/agent-instruction evidence only."""
import json, os, re, glob, csv

HARVEST = "/home/user/TRADING-BOT/project/trading_project/docs/research/huddleston_study/harvest"
DISTILL = os.path.join(HARVEST, "distill")
DR = "/tmp/dr"

LLM_PAT = re.compile(r"(generated by|generated with|claude|chatgpt|gpt-?4|gpt-?5|\bllm\b|ai-generated|ai generated|opencode|copilot|agent-generated|this (?:file|repo\w*) (?:was|is) (?:generated|maintained)|llm-maintainable|prompt)", re.I)
HUMAN_PAT = re.compile(r"(\bi wrote\b|\bmy (?:own )?notes\b|hand-?written|\bi (?:have )?(?:been )?trad\w*|my journal|\bi am (?:a|an)\b|\bmy personal\b)", re.I)
ARTIFACT = re.compile(r"(\[Music\]|\[Applause\]|\[ __ \]|♪|&gt;&gt;|>>\s|\[inaudible\])", re.I)

def read(p):
    try:
        return open(p, encoding="utf-8", errors="replace").read()
    except Exception:
        return ""

def first_line(path, pat, limit=25):
    for i, ln in enumerate(read(path).splitlines(), 1):
        if pat.search(ln):
            w = " ".join(ln.strip().split())
            return (i, " ".join(w.split()[:limit]))
    return None

def transcript_inventory():
    meta = {json.loads(l)["full_name"]: json.loads(l) for l in open(os.path.join(HARVEST, "github", "repos_meta.jsonl"))}
    base = os.path.join(DR, "newsqlguru__ict-index", "transcriptions")
    rows = []
    for p in sorted(glob.glob(base + "/**/*.json", recursive=True)):
        rel = os.path.relpath(p, os.path.join(DR, "newsqlguru__ict-index"))
        raw = read(p)
        size = os.path.getsize(p)
        ts = "yes" if ('"offsetMS"' in raw or '"offset"' in raw) else "no"
        arts = len(ARTIFACT.findall(raw))
        # caption artifact patterns present
        kinds = []
        if "[Music]" in raw: kinds.append("Music")
        if "[Applause]" in raw: kinds.append("Applause")
        if "&gt;&gt;" in raw or ">>" in raw: kinds.append("chevron")
        try:
            d = json.loads(raw)
            nseg = len(d) if isinstance(d, list) else 0
        except Exception:
            nseg = -1
        season = rel.split("/")[1] if rel.count("/") > 1 else ""
        ep = ""
        m = re.search(r"(Episode[-_ ]?0*(\d+))", os.path.basename(p))
        if m: ep = m.group(2)
        rows.append(dict(path=rel, bytes=size, has_timestamps=ts, segments=nseg,
                         caption_artifact_hits=arts, caption_artifact_kinds=";".join(kinds) or "none",
                         series=season, episode=ep or "", file=os.path.basename(p)))
    with open(os.path.join(DISTILL, "transcript_inventory.tsv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()), delimiter="\t")
        w.writeheader(); w.writerows(rows)
    return rows

def authorship():
    meta = [json.loads(l) for l in open(os.path.join(HARVEST, "github", "repos_meta.jsonl"))]
    out = []
    for m in meta:
        fn = m["full_name"]; d = os.path.join(DR, fn.replace("/", "__"))
        cands = []
        for name in ("README.md", "README", "AGENTS.md", "CLAUDE.md", "SKILL.md", "CONTRIBUTING.md", "readme.md"):
            p = os.path.join(d, name)
            if os.path.exists(p): cands.append(p)
        # any root-level *.md
        cands += [p for p in glob.glob(os.path.join(d, "*.md")) if p not in cands]
        flag, ev, evf, evline = "NO_SIGNAL", "", "", ""
        llm = None; hum = None
        for p in cands:
            if not llm:
                r = first_line(p, LLM_PAT)
                if r: llm = (os.path.relpath(p, d), r[0], r[1])
            if not hum:
                r = first_line(p, HUMAN_PAT)
                if r: hum = (os.path.relpath(p, d), r[0], r[1])
        if llm:
            flag, (evf, evline, ev) = "LLM_STATED", llm
        elif hum:
            flag, (evf, evline, ev) = "HUMAN_STATED", hum
        out.append(dict(full_name=fn, commit_sha=m["commit_sha"], kind_license=m.get("license") or "NONE",
                        flag=flag, evidence_file=evf, evidence_line=evline, evidence_quote=ev))
    with open(os.path.join(DISTILL, "authorship_flags.tsv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0].keys()), delimiter="\t")
        w.writeheader(); w.writerows(out)
    return out

if __name__ == "__main__":
    t = transcript_inventory(); a = authorship()
    from collections import Counter
    print("transcripts:", len(t), "with timestamps:", sum(1 for r in t if r["has_timestamps"] == "yes"),
          "with artifacts:", sum(1 for r in t if r["caption_artifact_hits"]))
    print("authorship:", Counter(x["flag"] for x in a))
    for x in a:
        if x["flag"] != "NO_SIGNAL":
            print(f"  {x['flag']:<12} {x['full_name']:<50} {x['evidence_file']}:{x['evidence_line']} :: {x['evidence_quote'][:90]}")
