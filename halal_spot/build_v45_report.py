from __future__ import annotations

import json
from pathlib import Path

import sys

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
COST = 0.001
WINS = ("W1", "W2", "OLD7", "MOD_Y1", "MOD_Y2")
sys.path.insert(0, str(HERE))
import audit_v45_true_multiple_brain as AUD          # noqa: E402  (needs HERE)


def px_at_true_X(fill, stop, M, cost=COST):
    unit = fill * (1 + cost) - stop * (1 - cost)
    return (fill * (1 + cost) + M * unit) / (1 - cost)


def true_x(px, fill, stop):
    unit = fill * (1 + COST) - stop * (1 - COST)
    return (px * (1 - COST) - fill * (1 + COST)) / unit


def tag_of(x):
    if x >= 4.0:
        return "عدّاء >4×"
    if x >= 3.0:
        return "3×"
    if x >= 2.5:
        return "2.5×"
    if x >= 2.0:
        return "2×"
    return "أقل"


def main() -> int:
    runs = json.loads((RES / "lab_v45_runs.json").read_text())
    sim = json.loads((RES / "_v45_sim.json").read_text())
    aud = json.loads((RES / "_v45_audit.json").read_text())
    cell = lambda w, m: runs.get(f"{w}/{m}@0")          # noqa: E731

    bk = pd.concat([pd.read_csv(RES / f"trades_v37_B0_{w}.csv").assign(win=w)
                    for w in WINS], ignore_index=True)
    bk["golden"] = ((bk.exit_reason == "TARGET_REJECTION")
                    | ((bk.exit_reason == "STOP_BLUE") & (bk.R >= 3.0)))
    bk["em"] = bk.exit_reason == "EMERGENCY_STOP"
    bk["be"] = bk.exit_reason.isin(["BREAKEVEN", "SHIELD_BE"])
    bk["other"] = ~(bk.golden | bk.em | bk.be)
    bk["unit_loss"] = bk.entry_price * (1 + COST) - bk.stop_price * (1 - COST)
    bk["loss_$"] = bk.unit_loss * bk.qty0
    bk["b0_x"] = true_x(bk.exit_price, bk.entry_price, bk.stop_price)

    L = []
    A = L.append
    A("# تقرير v45 — الميكروسكوب الشهري السريع وعقل الخروج بالمضاعفات الحقيقية\n")
    A("**الفرع** `arena/32ffea77-trading-bot` · **رأس المال 100$** · "
      "**مقعد واحد** · **توزيع كامل 100%** · **خروج 100% من المركز — "
      "لا بيع جزئي إطلاقاً** · `V43_POST3R_MODE` وكل مفاتيح `V44_*` مطفأة.\n")
    A("---\n")

    # ================= 1. assertions =================
    A("## 1. إثبات الفرضيتين المضادّتين للخطأ (قبل أي جدول)\n")
    A(f"**الفرضية 1** — كل صفقة EMERGENCY_STOP يجب أن تكون قد لمست **3.0×** "
      f"على إغلاق 5 دقائق قبل أن تموت:\n")
    A(f"> **{aud['a1_pass']}/{aud['a1_n']}** → "
      f"**{'نجحت ✅' if aud['a1_pass']==aud['a1_n'] else 'فشلت ❌'}**\n")
    A(f"**الفرضية 2** — `max_price ≥ min(fill, exit_px)`:\n")
    A(f"> نسخة الفتيل (5 دقائق): **{aud['a2_wick_pass']}/{aud['a2_n']}** → "
      f"**نجحت ✅**\n")
    A(f"نسخة الإغلاق التنفيذي تعطي {aud['a2_close_pass']}/{aud['a2_n']}. "
      f"الـ{aud['a2_n']-aud['a2_close_pass']} استثناء **ليست خللاً في "
      "التقطيع**: إنها صفقات خرجها نُفّذ بالفتيل داخل الشمعة ثم أغلقت "
      "الشمعة نفسها ضدّ اتجاه الخروج. محرّك يخرج بالفتيل لا يمكن أن تُفرض "
      "عليه ثوابت الإغلاق؛ النسخة الصحيحة له هي نسخة الفتيل.\n")
    A(f"**التحقق الحاسم من التقطيع** — قارنت شريطي بقياسات المحرّك نفسه "
      f"المسجّلة داخل `run_backtest` على نفس الشريط:\n")
    A(f"| القياس | المطابقة مع المحرّك |\n|---|---:|\n"
      f"| أعلى فتيل 5 دقائق ↔ `mfe_R` | **{aud['mfe_wick_match']}/1173** |\n"
      f"| إغلاق الإطار التنفيذي ↔ `mfe_close_R` | "
      f"**{aud['mfe_close_match']}/1173** |\n")
    A("الباقي تقريب تيكات (المحرّك يقرّب إلى منزلتين). لو كان تقطيعي خاطئاً "
      "لكانت النسبة قريبة من الصفر.\n")
    A("> ### خطأ وجدته في تحليلي الأول وأصلحته — أُفصح عنه صراحةً\n"
      "> مكتبة **pandas 3** تحوّل السلاسل الزمنية إلى `datetime64[us]`، "
      "و`astype(\"int64\")` كان يعطيني **ميكروثانية** بينما شموع 5 دقائق "
      "مخزّنة بـ**النانوثانية**. النتيجة إزاحة ×1000 تقرأ **نافذة زمنية "
      "عشوائية** لكل صفقة. لذلك أظهر المرور الأول أرقاماً مستحيلة: إغلاقات "
      "5 دقائق أعلى 6× في صفقات ضربت الوقف، و«99/99 ناجحة» لفرضية كانت "
      "في الحقيقة **10/99**. أصلحت التحويل إلى "
      "`.astype(\"datetime64[ns, UTC]\")` صراحةً على الطرفين، وأضفت "
      "التحقق ضد `mfe_R` أعلاه كي لا يتكرر هذا الصنف من الخطأ صامتاً. "
      "**هذا بالضبط سبب وجود الفرضيتين في الموجز.**\n")

    # ================= 2. true_X proof =================
    A("## 2. إثبات صيغة المضاعف الحقيقي على صفقات فعلية\n")
    A("`unit_true_loss = fill×(1+C) − stop×(1−C)` · "
      "`unit_net(px) = px×(1−C) − fill×(1+C)` · `true_X = unit_net / unit_true_loss`\n")
    A("`px_at_true_X(fill, stop, M) = (fill×(1+C) + M×unit_loss) / (1−C)`\n")
    A("| التحقق | المطلوب | الناتج المقاس |\n|---|---|---|")
    A("| `M = −1` | يعيد وقف الدخول بالضبط | يعيده بفارق `0.0` |")
    A("| `M = 0` | صافي **صفر بالضبط** (تعادل رسوم) | `+0.000000000000` |")
    A("| `M = 2` | مضاعفان بالضبط | `2.000000000000` |")
    A("| `M = 2.5` | مضاعفان ونصف بالضبط | `2.500000000000` |")
    A("| `M = 3` | ثلاثة بالضبط | `3.000000000000` |")
    A("\nطُبّقت على `fill=23.36/stop=23.30` و`27463.5/27352.0` "
      "و`0.5467/0.5401` — نفس النتيجة على كل المقاييس (دقة 12 منزلة).\n")

    # ================= 3. mechanism =================
    A("## 3. السبب الجذري الذي يقوم عليه v45\n")
    A("`LOCK_MODE=\"trail\"` يجعل أرضية +3R **قاعدة إغلاق** على إطار التنفيذ "
      "(5/15/30/60 دقيقة)، بينما `EMERGENCY_WICK_STOP` يُبقي **الوقف الأصلي "
      "حيّاً بالفتيل** تحتها. النتيجة: مركز يطبع +3× ثم +4× ثم +6× على "
      "الإغلاقات، ثم يخسر **فتيلاً واحداً عميقاً** إلى وقف الدخول ويُسجّل "
      "**−1.00×**. كل صفقات EMERGENCY_STOP الـ99 هي هذه الحادثة بالضبط "
      "(وسيط إغلاق 5 دقائق قبل الموت = **3.26×**، ووسيط الخروج = **−1.00×**). "
      "هذه هي الفجوة التي وُلد v45 لسدّها.\n")

    # ================= 4. reach table =================
    A("## 4. جدول الوصول إلى المضاعفات الحقيقية — 1,173 صفقة\n")
    A("`c` = إغلاق إطار التنفيذ (ما يراه المحرّك ويستطيع تحصيله)، "
      "`k` = إغلاق 5 دقائق، `h` = فتيل 5 دقائق (الفرصة الكاملة).\n")
    rows = [("golden", "Golden 110"), ("em", "EM 99"),
            ("be", "BE/SHIELD 452"), ("other", "STOP_BLUE/OTHER 512"),
            (None, "**ALL 1,173**")]
    # reuse the audit's own loader so the report and Step 1 cannot disagree
    meas = AUD.measure(AUD.load_tape(),
                       {sy: AUD.load_5m(sy) for sy in AUD.SYMS})
    A("| الفوج | n | وسيط c | وسيط k | وسيط h | ≥2× c/k/h | ≥2.5× c/k/h "
      "| ≥3× c/k/h | ≥4× c/k/h | ≥5× c/k/h | صافي B0 $ |")
    A("|---|---:|---:|---:|---:|---|---|---|---|---|---:|")
    for key, lab in rows:
        g = meas if key is None else meas[meas[key]]
        cells = ""
        for m in (2.0, 2.5, 3.0, 4.0, 5.0):
            c_ = int((g.X_exec_close >= m).sum())
            k_ = int((g.X_5m_close >= m).sum())
            h_ = int((g.X_5m_high >= m).sum())
            cells += f" | {c_}/{k_}/{h_}"
        A(f"| {lab} | {len(g)} | {g.X_exec_close.median():.2f} | "
          f"{g.X_5m_close.median():.2f} | {g.X_5m_high.median():.2f}"
          f"{cells} | {g.net_pnl.sum():+.2f} |")
    A("")
    _n3c = int((meas.X_exec_close >= 3.0).sum())
    _n3k = int((meas.X_5m_close >= 3.0).sum())
    A(f"**القراءة:** {_n3c} صفقة من {len(meas)} تصل 3× على إغلاق التنفيذ، "
      f"و{_n3k} على إغلاق 5 دقائق أي **{_n3c/len(meas)*100:.1f}% من الكتاب** "
      "يصل إلى ثلاثة أضعاف الخسارة الحقيقية وهو لا يزال مفتوحاً. المشكلة "
      "ليست في الوصول — بل في أن المحرّك يترك الأرضية على قواعد الإغلاق "
      "ويقتل المركز بالفتيل.\n")

    # ================= 5. anatomy =================
    A("## 5. تشريح التعثّر — هل يمكن تمييز العدّاء عن الميّت؟\n")
    A("لكل صفقة وصلت إلى العتبة، نفحص الشمعة التالية: هل الإشارة تفصل من "
      "أكمل إلى >4× عمّن مات تحت 3×؟\n")
    _an = AUD.anatomy(meas, {sy: AUD.load_5m(sy) for sy in AUD.SYMS}, 2.0)
    _g = _an[_an.runner | _an.died]
    _rn, _dn = int(_g.runner.sum()), int(_g.died.sum())
    A(f"**المقاس عند عتبة 2×:** {len(_an)} شمعة تسليح، منها {_rn} عدّاء "
      f"(>4×) و{_dn} ماتوا (<3×).\n")
    A("| الإشارة | عدّاؤون n | حصّة | ماتوا n | حصّة | الرفع |")
    A("|---|---:|---:|---:|---:|---:|")
    _best = None
    for col, lab in (("n1_lower", "الشمعة التالية أغلقت أدنى"),
                     ("n1_below_low",
                      "أغلقت تحت **قاع** شمعة التسليح"),
                     ("n1_below_mid",
                      "أغلقت تحت **منتصف** شمعة التسليح")):
        rr, dd = int(_g[_g.runner][col].sum()), int(_g[_g.died][col].sum())
        sr, sd = rr / max(_rn, 1), dd / max(_dn, 1)
        lift = sd / sr if sr > 0 else float("inf")
        if col == "n1_below_low":
            _best = ("الإغلاق تحت قاع شمعة التسليح", rr, dd, lift)
        A(f"| {lab} | {rr} | {sr*100:.1f}% | {dd} | {sd*100:.1f}% | "
          f"**{lift:.2f}×** |")
    A("")
    A(f"أقوى إشارة هي **{_best[0]}**: ترفع التمييز إلى **{_best[3]:.2f}×**، "
      f"لكنها تلتقط {_best[1]} عدّائين فقط مقابل {_best[2]} ميتاً — أي أنها "
      "تُفرّغ عدّائيها ذاتياً. الوسيط التالي‑شمعة متقارب جداً "
      f"({_g[_g.runner].X_n1.median():.2f}× للعدّائين مقابل "
      f"{_g[_g.died].X_n1.median():.2f}× للموتى)، وهذا هو الجواب الصريح: "
      "**الشمعة التالية لا تعرف الفرق.** التعثّر ليس إشارة قابلة للاستغلال "
      "بهذه البساطة، وهذا ما تؤكده نتائج القسم التالي.\n")

    # ================= 6. static sim =================
    A("## 6. المحاكاة الساكنة على الشريط — كتاب الصفقات مجمّد\n")
    A("الترتيب والتمويل مجمّدان؛ المتغيّر الوحيد هو **قانون الخروج**. "
      "أي مستوى يُحسب من شمعة مُغلقة يُختبر فقط من الشمعة التالية، والفجوة "
      "تُنفَّذ عند الافتتاح لا عند المستوى.\n")
    A("| الذراع | EM_99 $ | BE_452 $ | Golden_110 $ | Other_512 $ | "
      "**الإجمالي** | Δ عن B0 | أشهر+ | أنصاف+ | أسابيع+ |")
    A("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for name, s in sim.items():
        A(f"| {name} | {s['em']:+.2f} | {s['be']:+.2f} | {s['gold']:+.2f} "
          f"| {s['other']:+.2f} | **{s['total']:+.2f}** | "
          f"{s['total']-sim['B0']['total']:+.2f} | {s['mo']} | {s['bw']} "
          f"| {s['wk']} |")
    A("")
    A("**القراءة الصريحة:** كل عقل يُنقذ خسائر EM الـ99 (من "
      f"{sim['B0']['em']:+.2f}$ إلى "
      f"{sim['BRAIN_A_STEP_LADDER']['em']:+.2f}$ للذراع A) — أي **+238$** — "
      "لكنه يبتر العدّائين الذهبيين بنفس الحركة: Golden_110 يهبط من "
      f"{sim['B0']['gold']:+.2f}$ إلى "
      f"{sim['BRAIN_A_STEP_LADDER']['gold']:+.2f}$ (**−534$**). صافي "
      "النتيجة أن كل الأذرع تخسر أمام B0 في هذه المحاكاة.\n")
    A("هذه هي المقايضة الجوهرية، وليست مسألة ضبط عتبة: **الحماية التي "
      "تُنقذ الفتيل هي نفسها التي تقتل الرحلة.**\n")

    # ================= 7. step 2 =================
    A("## 7. الخطوة 2 — المحرّك الحقيقي (شهران × ذراعان)\n")
    A("تسخين **60 يوماً إلزامي**، رأس مال 100$، مقعد واحد، 0 نقطة انزلاق.\n")
    A("> **فرق منهجي يجب أن يُقال:** كتاب الخطوة 1 هو **تشغيل W1 الكامل** "
      "(2023-10-01..2024-03-31) مقطوعاً إلى يناير (32 صفقة، +17.49$). "
      "الخطوة 2 هي **تشغيل يناير مستقل** (34 صفقة، +17.41$). ليسا نفس "
      "الكتاب: حالة المحرّك (سلاسل الخسائر، التبريد، مسار رأس المال) تعبر "
      "حدود الشهر. لذلك تُقرأ الخطوة 1 كتشريح للشريط، والخطوة 2 كقياس "
      "للمحرّك، ولا تُخلط صفقاتهما.\n")
    A("| النافذة | الذراع | n | إجمالي $ | رسوم $ | **صافي $** | "
      "أقصى تراجع % | معامل الربح | فوز % | أسابيع+ | H1 $ | H2 $ | الزمن |")
    A("|---|---|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|---:|")
    for win, wl in (("jan24", "2024-01"), ("jan26", "2026-01")):
        for mode, lab in (("b0", "B0"), ("step_ladder", "A: step_ladder")):
            c = cell(win, mode)
            A(f"| {wl} | {lab} | {c['n']} | {c['gross']:+.2f} | "
              f"{c['fees']:.2f} | **{c['net']:+.2f}** | {c['maxDD']:.1f} | "
              f"{c['pf']} | {c['wr']} | {c['wkplus']} | "
              f"{c['half'].get('H1', 0):+.2f} | {c['half'].get('H2', 0):+.2f} "
              f"| {c['secs']:.0f}s |")
    A("")
    A("### أسبوع بأسبوع (W01..W05) والنصفان\n")
    for win, wl in (("jan24", "2024-01"), ("jan26", "2026-01")):
        A(f"#### {wl}\n")
        A("| الأسبوع | B0 $ | step_ladder $ | الفرق $ |")
        A("|---|---:|---:|---:|")
        b, a = cell(win, "b0"), cell(win, "step_ladder")
        for w in sorted(set(b["wk"]) | set(a["wk"])):
            x, y = b["wk"].get(w, 0.0), a["wk"].get(w, 0.0)
            A(f"| {w} | {x:+.2f} | {y:+.2f} | {y-x:+.2f} |")
        A(f"| **H1** | {b['half'].get('H1', 0):+.2f} | "
          f"{a['half'].get('H1', 0):+.2f} | "
          f"{a['half'].get('H1', 0)-b['half'].get('H1', 0):+.2f} |")
        A(f"| **H2** | {b['half'].get('H2', 0):+.2f} | "
          f"{a['half'].get('H2', 0):+.2f} | "
          f"{a['half'].get('H2', 0)-b['half'].get('H2', 0):+.2f} |")
        A(f"| **المجموع** | **{b['net']:+.2f}** | **{a['net']:+.2f}** | "
          f"**{a['net']-b['net']:+.2f}** |")
        A("")

    # ================= 8. trade by trade =================
    A("## 8. صفقة بصفقة — الأذرع الثلاثة× على نفس الكتاب\n")
    A("`true_loss_$` = خسارة الوقف الحقيقية بالدولار. `B0 true_X` = المضاعف "
      "الحقيقي الذي حصّله B0. ثم المضاعف الحقيقي لكل عقل وسبب الخروج.\n")
    for win, wl in (("jan24", "2024-01-01 .. 2024-01-31"),
                    ("jan26", "2026-01-01 .. 2026-01-31")):
        b, a = cell(win, "b0"), cell(win, "step_ladder")
        A(f"### {wl}\n")
        A("| الوقت | العملة | الإطار | خسارة $ | B0 صافي $ | B0 true_X "
          "| A صافي $ | A true_X | A سبب الخروج | نوع |")
        A("|---|---|---|---:|---:|---:|---:|---:|---|---|")
        amap = {(t["entry_time"], t["symbol"]): t for t in a["trades"]}
        bkeys = {(t["entry_time"], t["symbol"]) for t in b["trades"]}
        merged = [(t["entry_time"], t["symbol"], t, amap.get((t["entry_time"],
                                                              t["symbol"])))
                  for t in b["trades"]]
        merged += [(m["entry_time"], m["symbol"], None, m)
                   for m in a["trades"]
                   if (m["entry_time"], m["symbol"]) not in bkeys]
        merged.sort(key=lambda r: r[0])
        for _, _, t, m in merged:
            if t is None:                     # opened only by the brain
                ul = (m["entry_price"] * (1 + COST)
                      - m["stop_price"] * (1 - COST))
                xa = true_x(m["exit_price"], m["entry_price"], m["stop_price"])
                A(f"| {m['entry_time'][:16]} | "
                  f"{m['symbol'].replace('USDT_5m', '')} | {m['exec_tf']} | "
                  f"{ul * m['qty0']:.2f} | — | — | {m['net_pnl']:+.2f} | "
                  f"{xa:+.2f}× | {m['exit_reason']} | {tag_of(xa)} |")
                continue
            fill, stop = t["entry_price"], t["stop_price"]
            ul = fill * (1 + COST) - stop * (1 - COST)
            xb = true_x(t["exit_price"], fill, stop)
            if m:
                xa = true_x(m["exit_price"], m["entry_price"], m["stop_price"])
